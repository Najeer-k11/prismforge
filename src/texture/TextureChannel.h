#pragma once

#include <QJsonObject>
#include <QList>
#include <QString>

#include <array>
#include <optional>

namespace pf {

// Shadertoy-style texture inputs. Shaders declare
//   uniform sampler2D uChannel0;   // ... uChannel3
//   uniform vec3 uChannelResolution[4]; // texture size in texels (z = 1)
// and PrismForge binds whatever texture the user chose for each channel.
inline constexpr int kChannelCount = 4;

enum class TextureFilter { Nearest, Linear, Mipmap };
enum class TextureWrap { Repeat, Clamp, Mirror };

QString toString(TextureFilter filter);
QString toString(TextureWrap wrap);
std::optional<TextureFilter> textureFilterFromString(const QString& name);
std::optional<TextureWrap> textureWrapFromString(const QString& name);

// How a channel's texture is uploaded and sampled.
struct ChannelSampler {
    TextureFilter filter = TextureFilter::Mipmap;
    TextureWrap wrap = TextureWrap::Repeat;
    // Upload the image bottom row first, so uv (0, 0) is the picture's
    // bottom-left corner (matches gl_FragCoord and Shadertoy's default).
    bool flipY = true;
    bool operator==(const ChannelSampler&) const = default;
};

struct ChannelBinding {
    enum class Source { None, Builtin, File };
    Source source = Source::None;
    // Built-in texture id, or an image file path. File paths are relative to
    // the project in *.pfproj files and absolute everywhere else.
    QString texture;
    ChannelSampler sampler;

    bool isEmpty() const { return source == Source::None; }
    bool operator==(const ChannelBinding&) const = default;
};

using ChannelBindings = std::array<ChannelBinding, kChannelCount>;

QString channelUniformName(int index); // "uChannel0"

// Only bound channels are written, keyed by index:
//   { "0": { "texture": "rgba-noise-256", "filter": "linear", "wrap": "repeat", "flipY": true },
//     "2": { "file": "textures/bricks.png", "filter": "mipmap", "wrap": "repeat", "flipY": true } }
QJsonObject channelsToJson(const ChannelBindings& channels);
// Malformed entries are skipped; unknown filter/wrap names fall back to defaults.
ChannelBindings channelsFromJson(const QJsonObject& json);

// Textures bundled with PrismForge (Qt resources :/textures/<id>.png),
// generated by tools/generate_textures.py. All of them tile seamlessly.
struct BuiltinTexture {
    QString id;
    QString name;
    QString description;
    ChannelSampler sampler; // recommended settings

    QString resourcePath() const { return QStringLiteral(":/textures/%1.png").arg(id); }
};

const QList<BuiltinTexture>& builtinTextures();
const BuiltinTexture* findBuiltinTexture(const QString& id);

// A binding to a built-in texture with its recommended sampler settings.
ChannelBinding builtinBinding(const QString& id);

} // namespace pf
